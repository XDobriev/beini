"""Generate the static JS and Go fallback from the reviewed seed; offline only."""
import argparse
import json
import subprocess
import tempfile
from pathlib import Path

from import_menu import export_js_menu_data

ROOT = Path(__file__).resolve().parents[1]


def go_catalog(catalog):
    lines = ['// Code generated by tools/export_menu.py; DO NOT EDIT.', 'package catalog', '',
             'var defaultBeiniItems = []Item{']
    for item in catalog['items']:
        if not item.get('available', True) or item.get('hidden'):
            continue
        fields = {'ID': item['id'], 'IikoID': item['iikoId'], 'Name': item['name'],
                  'SourceName': item['sourceName'], 'Price': item['price'], 'Category': item['category']}
        for source, target in (('variantGroup', 'VariantGroup'), ('variantName', 'VariantName'),
                               ('variantLabel', 'VariantLabel'), ('variantOrder', 'VariantOrder')):
            if source in item:
                fields[target] = item[source]
        lines.append('\t{' + ', '.join(key + ': ' + json.dumps(value, ensure_ascii=False)
                                     for key, value in fields.items()) + '},')
    # Existing synthetic tests use p1. It is never part of the runtime seed.
    lines.extend(['\t{ID: "p1", IikoID: "p1", Name: "Тестовое блюдо p1", Price: 590},', '}', ''])
    return subprocess.run(['gofmt'], input='\n'.join(lines), text=True,
                          encoding='utf-8', capture_output=True, check=True).stdout


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='verify generated files without writing')
    args = parser.parse_args()
    catalog = json.loads((ROOT / 'data/menu_catalog.json').read_text(encoding='utf-8'))
    if any(not item.get('sourceName', '').strip() for item in catalog['items']):
        parser.exit(1, 'Every item requires a reviewed sourceName\n')
    with tempfile.TemporaryDirectory(prefix='beini-export-') as directory:
        target = Path(directory) / 'menu-data.js'
        export_js_menu_data(catalog, target)
        outputs = {ROOT / 'js/menu-data.js': target.read_text(encoding='utf-8'),
                   ROOT / 'internal/catalog/catalog_data.go': go_catalog(catalog)}
        for path, text in outputs.items():
            if args.check:
                if not path.exists() or path.read_text(encoding='utf-8') != text:
                    parser.exit(1, f'Generated menu differs: {path.name}\n')
            else:
                path.write_text(text, encoding='utf-8', newline='\n')
    print('Generated menu files consistent' if args.check else 'Exported reviewed JS/Go menu')


if __name__ == '__main__':
    main()
